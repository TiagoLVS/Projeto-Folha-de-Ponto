-- Login: contas locais e sessões compartilhadas pelas máquinas via PostgreSQL principal.
-- A primeira conta administradora é criada na interface do computador principal.
CREATE TABLE IF NOT EXISTS usuario_sistema (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(50) NOT NULL UNIQUE,
    senha_hash TEXT NOT NULL,
    administrador BOOLEAN NOT NULL DEFAULT FALSE,
    tentativas_falhas INTEGER NOT NULL DEFAULT 0,
    bloqueado_ate TIMESTAMPTZ,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    ultimo_login TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS sessao_sistema (
    token_hash CHAR(64) PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario_sistema(id_usuario) ON DELETE CASCADE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_em TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_sessao_sistema_expira_em ON sessao_sistema(expira_em);
